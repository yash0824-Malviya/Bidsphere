import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync, readdirSync } from "node:fs";
import { createEcrSchemaErpClient, ecrSchemaResource as resource, listAllEcrSchemaRows } from "../scripts/ecr-schema-erp-client.mjs";
const api = createEcrSchemaErpClient();
const ECR = "Engineering Change Request";
const hash = (value) => createHash("sha256").update(JSON.stringify(value)).digest("hex");
const directory = readdirSync(new URL("./", import.meta.url)).filter((name) => name.startsWith("ecr-source-schema-repair-")).sort().at(-1);
const before = JSON.parse(readFileSync(new URL(`./${directory}/before.json`, import.meta.url), "utf8"));
const rows = await listAllEcrSchemaRows(api, ECR, ["name", "select_pxfp", "docstatus", "modified"]);
const records = [];
for (const row of rows) records.push(await api("GET", resource(ECR, row.name)));
assert.equal(hash(rows), hash(before.recordMetadata));
assert.equal(hash(records), before.recordFingerprint);
const workflows = [];
for (const workflow of before.workflows) workflows.push(await api("GET", resource("Workflow", workflow.name)));
assert.equal(hash(workflows), hash(before.workflows));
const setters = await listAllEcrSchemaRows(api, "Property Setter", ["name", "field_name", "property", "value", "property_type"], [["doc_type", "=", "ECR Affected Part"], ["field_name", "=", "source_reference_type"]]);
const meta = await api("GET", `method/frappe.desk.form.load.getdoctype?${new URLSearchParams({ doctype: "ECR Affected Part", with_parent: "0" })}`);
console.log(JSON.stringify({ recordsUnchanged: records.length, workflowsUnchanged: workflows.length, propertySetters: setters, effectiveFields: (meta.docs || []).filter((doc) => doc.name === "ECR Affected Part").flatMap((doc) => (doc.fields || []).filter((field) => field.fieldname === "source_reference_type").map((field) => ({ fieldname:field.fieldname, options:field.options, default:field.default, reqd:field.reqd }))) }, null, 2));
